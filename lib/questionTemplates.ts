export function findTemplate(id: string): QuestionTemplate | undefined {
  return QUESTION_TEMPLATES.find((t) => t.id === id);
}

// 内容の欄が「空」または「テンプレートのまま」なら、上書きしても失うものがない
export function isUntouchedBody(current: string): boolean {
  const c = current.trim();
  if (c === "") return true;
  return QUESTION_TEMPLATES.some((t) => t.body.trim() === c);
}
